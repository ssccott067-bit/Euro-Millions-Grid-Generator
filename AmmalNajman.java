import java.util.ArrayList;

class AmmalNajman extends Prediction {

    public int[] predictionTirage(ListeTirage listeTirage) { // static

        /*
            Conditions :
            1. 30 numeros les plus tires (par nombre de tirage)
            2. 10 etoiles les plus tirees (par nombre de tirage)
            3. 20 numeros les plus recents parmi les 30 precedemment tries (par jours)
            4. 5 etoiles les plus recents parmi les 10 precedemment triees (par jours)
            5. Les rangements de numeros et etoiles sont fait au hasard (aleatoirement)
                > pour prendre l'essence du jeu :)


            // Explication de strategie :

            (Statictically, by the concept of Normal Distribution, *The Law of Large Numbers, and the statistic
            of each number [1 - 50] (and star [1 - 12]), we can conclude that we will have a bigger chance of winning 
            if we let a reasonable amount of number to be chosen (so the stars) 
            that is closed to the min (equally median & mod) of the distribution of the numbers (so the stars), 
            this is also valid (theoretically) since we have a large number of sample 
            (note that we took into account all the draw that are made between September 2016 until today)
            so, the expected number to be appear will be between the min (variation) of the distribution.
            
            Another factor that we took into account is the date of the last draw
            (even if a number have a high probability to be choose but if it has not been chosen for a long time,
            it will (theoretically) reduce its chance to appear), however this factor is not yet proven to be true (nor false).

            One might argue that the draw is randomly generated by the computer,
            but the statistic and data serve us as a good reason to believe that there is a little manipulation behind the draw.
            
            In conclusion, we can choose 5 numbers out of 20 that have been carefully sort by the two caracteristics among the 50 and
            we can choose 2 stars out of 10 that have been carefully sort by the two caracteristics among the 12.
            So, we will have a feasibly reasonable number and star to choose from.)

            * Law of Large Number (Random Variation), Abraham de Moivre; 
                The larger the sample size, the smaller the random variation.
                So, the estimated value of a parameter becomes more consistent. 
        */


        // recuperer les frequency (counts) de chaque nombres et etoiles
        // plages pour les counts 
        int[][] plageNumerosCount = new int[50][2];
        int[][] plageEtoilesCount = new int[12][2];

        // plageNumerosCount
        for (int i=0; i<50; i++) {

            plageNumerosCount[i][0] = listeTirage.nbTiragePourNumero(i+1); // count
            plageNumerosCount[i][1] = i+1; // numero
        }

        // plageEtoilesCount
        for (int j=0; j<12; j++) {

            plageEtoilesCount[j][0] = listeTirage.nbTiragePourEtoile(j+1); // count
            plageEtoilesCount[j][1] = j+1; // etoile
        }


        // trier les numeros et etoiles par le maximum de count 
        // trier les numeros (count)
        for (int k=0; k<50; k++) {

            for (int l=k+1; l<50; l++) {

                if (plageNumerosCount[l][0] > plageNumerosCount[k][0]) {

                    int[] temp = plageNumerosCount[k];
                    plageNumerosCount[k] = plageNumerosCount[l];
                    plageNumerosCount[l] = temp;
                }
            }
        }

        // trier les etoiles (count)
        for (int o=0; o<12; o++) {

            for (int p=o+1; p<12; p++) {

                if (plageEtoilesCount[p][0] > plageEtoilesCount[o][0]) {

                    int[] temp = plageEtoilesCount[o];
                    plageEtoilesCount[o] = plageEtoilesCount[p];
                    plageEtoilesCount[p] = temp;
                }
            }
        }


        // copier les nombres et etoiles 
        // plage pour les numeros et etoiles tries
        int[] numerosFre = new int[30];
        int[] etoilesFre = new int[10];

        // gerer les numeros 
        for (int m=0; m<30; m++) {

            numerosFre[m] = plageNumerosCount[m][1];
        }

        // gerer les etoiles 
        for (int n=0; n<10; n++) {

            etoilesFre[n] = plageEtoilesCount[n][1];
        }


        // recuperer les jours pour numeros et etoiles
        // plages pour les jours 
        Date dateNumeros = new Date();
        Date dateEtoiles = new Date();
        long[][] plageNumerosJour = new long[30][2];
        long[][] plageEtoilesJour = new long[10][2];

        // plageNumerosJour
        for (int t=0; t<30; t++) {

            dateNumeros = listeTirage.dateDernierTiragePourNumero(numerosFre[t]);
            plageNumerosJour[t][0] = dateNumeros.calculerDifference();
            plageNumerosJour[t][1] = numerosFre[t];
        }

        // plageEtoilesJour
        for (int y=0; y<10; y++) {

            dateEtoiles = listeTirage.dateDernierTiragePourEtoile(etoilesFre[y]);
            plageEtoilesJour[y][0] = dateEtoiles.calculerDifference();
            plageEtoilesJour[y][1] = etoilesFre[y];
        }


        // trier les numeros et etoiles par jour le plus recent 
        // trier les numeros
        for (int z=0; z<30; z++) {

            for (int x=z+1; x<30; x++) {

                if (plageNumerosJour[x][0] < plageNumerosJour[z][0]) {

                    long[] temp = plageNumerosJour[z];
                    plageNumerosJour[z] = plageNumerosJour[x];
                    plageNumerosJour[x] = temp;
                }
            }
        }

        // trier les etoiles
        for (int a=0; a<10; a++) {

            for (int f=a+1; f<10; f++) {

                if (plageEtoilesJour[f][0] < plageEtoilesJour[a][0]) {

                    long[] temp = plageEtoilesJour[a];
                    plageEtoilesJour[a] = plageEtoilesJour[f];
                    plageEtoilesJour[f] = temp;
                }
            }
        }


        // copier les numeros et etoiles
        // plage pour les numeros et etoiles 
        int[] numerosJour = new int[20];
        int[] etoilesJour = new int[5];

        // numeros 
        for (int r=0; r<20; r++) {

            numerosJour[r] = (int) plageNumerosJour[r][1];
        }

        // etoiles 
        for (int w=0; w<5; w++) {

            etoilesJour[w] = (int) plageEtoilesJour[w][1];
        }



        // The Big Guy 
        // selectionner les meilleurs nombres et etoiles (aleatoirement)
        int[] monTirage = new int[7];
        ArrayList<Integer> nums = new ArrayList<>();
        ArrayList<Integer> etoils = new ArrayList<>();

        // stocker les index de numeros
        for (int number=0; number<20; number++) {

            nums.add(number); // adding all the index for numeros (0 - 19)
        }

        // stocker les index d'etoiles
        for (int star=0; star<5; star++) {

            etoils.add(star); // adding all the index for etoiles (0 - 4)
        }

        // chercher les bons nombres (aleatoirement)
        for (int t=0; t<5; t++) {

            int randomN = (int)(Math.random()*nums.size());     // generate a number between 0 - 19
            int indexRandomN = nums.get(randomN);               // get the index from the liste of index (to ensure it is random)
            monTirage[t] = numerosJour[indexRandomN];           // get the number of numeros (1 - 20)
            nums.remove(randomN);                               // remove the numeros to avoid repetition
        }    
        
        // chercher les bons etoiles (aleatoirement)
        for (int s=0; s<2; s++) {

            int randomS = (int)(Math.random()*etoils.size());
            int indexRandomS = etoils.get(randomS);
            monTirage[s+5] = etoilesJour[indexRandomS];
            etoils.remove(randomS);
        }

        // return the winning draw 
        return monTirage;
    }
}
